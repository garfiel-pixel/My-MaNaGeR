#!/usr/bin/env node
/* ============================================================
   verify-wiring.cjs - Wave 7: the wiring gate (owner 2026-11-10)
   ------------------------------------------------------------
   A control that looks alive but has no handler is the defect class this
   project keeps hitting ("I click it and nothing happens"). This gate reads
   the SERVED markup and the ACTION maps and fails when the two disagree:

     1. every data-action in a served .html must exist in an ACTION map
        (mmgr-app.js ACTION_MAP or admin.html ADMIN_ACTION_MAP), unless it is
        on the allowlist below;
     2. every ACTION-map key must be referenced as a quoted string somewhere
        in the served markup or JS (a truly dead handler), unless allowlisted;
     3. the delegated families named in the plan (data-cd-*, data-team-*,
        data-bmg, data-rail-toggle, data-consent-*) must each have a handler
        in JS;
     4. every local href="*.html" in a served page must resolve to a file.

   The allowlist is deliberately TIGHT and starts with today's genuine
   dynamic-only actions. Shrink it as each wave lands.

   Run: node tools/verify-wiring.cjs
   ============================================================ */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

let failures = 0;
function fail(msg) {
  failures++;
  console.error('  FAIL  ' + msg);
}
function pass(msg) {
  console.log('  PASS  ' + msg);
}

// Actions that only ever appear from dynamic rows or from a page this gate
// does not serve (the admin panel's own generated rows). Keep this list short.
const ACTION_ALLOW = new Set([
  // generated by the launcher/cloud dash at runtime
  'cdCopy',
  'cdDelete',
  'cdUnpin',
  'cdOpen',
  // generated by team-ui.js at runtime
  'teamBell',
  'teamAccept',
  'teamDecline',
  // generated by the AI actions preview card
  'aiApplyActions',
  'aiDismissActions',
  // generated by the procurement/BOQ rows
  'procQuote',
  'procAccept'
]);

// Extract top-level keys from a `const NAME = {` object literal.
function extractMapKeys(src, name) {
  const lines = src.split('\n');
  const keys = [];
  let inMap = false;
  let depth = 0;
  const start = new RegExp('(?:const|let|var)\\s+' + name + '\\s*=\\s*\\{');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!inMap && start.test(line)) {
      inMap = true;
      depth = 0;
    }
    if (!inMap) {
      continue;
    }
    // Count braces outside strings/comments is overkill here: the maps are
    // written one key per line and nested objects are rare. Depth tracking
    // still keeps us out of nested blocks.
    const opens = (line.match(/\{/g) || []).length;
    const closes = (line.match(/\}/g) || []).length;
    if (depth === 1) {
      const m = line.match(/^\s{2,6}['"]?([A-Za-z_$][\w$]*)['"]?\s*:/);
      if (m) {
        keys.push(m[1]);
      }
    }
    depth += opens - closes;
    if (depth <= 0 && i > 0) {
      break;
    }
  }
  return keys;
}

function read(p) {
  return fs.readFileSync(path.join(ROOT, p), 'utf8');
}
function walk(dir, out) {
  for (const name of fs.readdirSync(path.join(ROOT, dir))) {
    const rel = dir + '/' + name;
    const full = path.join(ROOT, rel);
    if (fs.statSync(full).isDirectory()) {
      if (name === 'node_modules' || name === 'dist' || name === 'tmp') {
        continue;
      }
      walk(rel, out);
    } else if (name.endsWith('.js')) {
      out.push(rel);
    }
  }
  return out;
}

// ---- collect ------------------------------------------------------------
const htmlFiles = fs
  .readdirSync(ROOT)
  .filter(f => f.endsWith('.html'))
  .sort();
const jsFiles = walk('js', []);

const appSrc = read('js/mmgr-app.js');
const adminSrc = read('admin.html');
const calcSrc = read('js/calculator-page.js');
const dashSrc = read('app.html');
const appMap = new Set(extractMapKeys(appSrc, 'ACTION_MAP'));
const adminMap = new Set(extractMapKeys(adminSrc, 'ADMIN_ACTION_MAP'));
const calcMap = new Set(extractMapKeys(calcSrc, 'ACTIONS'));
const dashMap = new Set(extractMapKeys(dashSrc, 'DASH_ACTION_MAP'));
const handlers = new Set([...appMap, ...adminMap, ...calcMap, ...dashMap]);

if (handlers.size < 20) {
  fail('ACTION maps look empty (' + handlers.size + ' keys) - parser is stale');
}

// Every data-action value in served HTML.
const htmlAction = new Map(); // value -> [file]
for (const f of htmlFiles) {
  const src = read(f);
  const re = /data-action\s*=\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(src))) {
    if (!htmlAction.has(m[1])) {
      htmlAction.set(m[1], []);
    }
    htmlAction.get(m[1]).push(f);
  }
}

// Every quoted data-action value in JS (dynamic markup).
const jsAction = new Set();
for (const f of jsFiles) {
  const src = read(f);
  const re = /data-action\s*=\s*\\?["']([^"'\\]+)/g;
  let m;
  while ((m = re.exec(src))) {
    jsAction.add(m[1]);
  }
  const re2 = /getAttribute\(\s*['"]data-action['"]\s*\)/g;
  void re2;
}

// ---- 1. attribute -> handler -------------------------------------------
console.log('\n=== 1. data-action in served HTML has a handler ===\n');
let attrFails = 0;
for (const [action, files] of htmlAction) {
  if (handlers.has(action) || ACTION_ALLOW.has(action)) {
    continue;
  }
  fail('data-action="' + action + '" has no handler (' + files.join(', ') + ')');
  attrFails++;
}
if (attrFails === 0) {
  pass('all ' + htmlAction.size + ' HTML data-action values have a handler');
}

// ---- 2. handler -> attribute (dead handler) -----------------------------
// Reported as a WARNING, not a failure: many handlers are reached only from
// markup built at runtime (a `data-action="' + x + '"` template or a
// programmatic .click()), so a static "never referenced" reading is a hint,
// not proof. The direction that catches a dead BUTTON (section 1) is enforced.
console.log('\n=== 2. handler references (informational) ===\n');
let deadWarn = 0;
for (const key of handlers) {
  const quoted = new RegExp('["\']' + key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '["\']');
  let used = htmlAction.has(key) || jsAction.has(key);
  if (!used) {
    for (const f of htmlFiles) {
      if (quoted.test(read(f))) {
        used = true;
        break;
      }
    }
  }
  if (!used) {
    for (const f of jsFiles) {
      if (quoted.test(read(f))) {
        used = true;
        break;
      }
    }
  }
  if (!used && !ACTION_ALLOW.has(key)) {
    console.log('  WARN  handler "' + key + '" has no static reference (dynamic only?)');
    deadWarn++;
  }
}
pass(handlers.size + ' handlers scanned (' + deadWarn + ' dynamic-only, informational)');

// ---- 3. delegated families ---------------------------------------------
console.log('\n=== 3. delegated data-* families have a handler ===\n');
const families = [
  { token: 'data-cd-load', where: 'js/mmgr-cloud-dash.js' },
  { token: 'data-cd-copy', where: 'js/mmgr-cloud-dash.js' },
  { token: 'data-cd-menu', where: 'js/mmgr-cloud-dash.js' },
  { token: 'data-team-bell', where: 'js/cloud/team-ui.js' },
  { token: 'data-team-accept', where: 'js/cloud/team-ui.js' },
  { token: 'data-team-revoke', where: 'js/cloud/team-ui.js' },
  { token: 'data-bmg', where: 'js/mmgr-billing-manage.js' },
  { token: 'data-rail-toggle', where: 'app.html' },
  { token: 'data-consent-open', where: 'js/consent.js' }
];
let famFails = 0;
for (const fam of families) {
  const src = read(fam.where);
  if (src.indexOf(fam.token) === -1) {
    fail(fam.token + ' has no handler in ' + fam.where);
    famFails++;
  }
}
if (famFails === 0) {
  pass('all ' + families.length + ' delegated families have a handler');
}

// ---- 4. local links -----------------------------------------------------
console.log('\n=== 4. local page links resolve ===\n');
let linkFails = 0;
let linkCount = 0;
for (const f of htmlFiles) {
  const src = read(f);
  const re = /href\s*=\s*"([^"#?]+\.html)(?:[?#][^"]*)?"/g;
  let m;
  while ((m = re.exec(src))) {
    const target = m[1];
    if (/^https?:|^\/\//.test(target)) {
      continue;
    }
    linkCount++;
    const rel = target.replace(/^\//, '');
    if (!fs.existsSync(path.join(ROOT, rel))) {
      fail(f + ' links to a missing page: ' + target);
      linkFails++;
    }
  }
}
if (linkFails === 0) {
  pass('all ' + linkCount + ' local page links resolve');
}

// ---- summary ------------------------------------------------------------
console.log('\n' + (failures === 0 ? 'ALL CHECKS PASSED' : failures + ' FAILURE(S) FOUND'));
process.exit(failures === 0 ? 0 : 1);

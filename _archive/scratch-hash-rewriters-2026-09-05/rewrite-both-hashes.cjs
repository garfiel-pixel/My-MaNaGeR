// Count hashes / defs in both after rewrite.
function countHashes(file){
  const src = fs.readFileSync(file, 'utf8');
  const m = src.match(/const INLINE_SCRIPT_HASHES = \[([^\]]+)\]\.join\(' '\)/);
  if (!m) return { defs: (src.match(/const INLINE_SCRIPT_HASHES = \[/g)||[]).length, hashes: 0 };
  const hashes = (m[1].match(/sha256/g)||[]).length;
  return { defs: (src.match(/const INLINE_SCRIPT_HASHES = \[/g)||[]).length, hashes };
}

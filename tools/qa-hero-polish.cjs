// T-HERO gate (Wave I, I-4 hero polish).
// Asserts the computed styles of the landing hero after the I-4 changes:
//   - View Field Guide (.btn-ghost-light): no glass, no white, gold text, no border
//   - Get Started (.btn-gold): no outline / border
//   - globe feature cards (.hg-card): no gold outline (transparent border)
//   - hero gold headline words (.hero h1 .gold): gold token + display serif
//   - typed text present in the DOM at load (.hero-type + .hero-sub)
// Runs against the shared QA server (:8765 by default, MMGR_BASE to override).

const { chromium } = require('playwright');

const BASE = process.env.MMGR_BASE || 'http://127.0.0.1:8765';
const URL = BASE + '/index.html';

let pass = 0;
let fail = 0;
const fails = [];
function ok(name) {
  pass++;
  console.log('  PASS', name);
}
function bad(name, detail) {
  fail++;
  fails.push(name + ': ' + detail);
  console.log('  FAIL', name, '-', detail);
}

(async () => {
  let launchOpts = { headless: true };
  try {
    const cp = require('./chrome-launcher.cjs').chromePath;
    if (cp) launchOpts.executablePath = cp;
  } catch (e) {}
  const browser = await chromium.launch(launchOpts);
  const ctx = await browser.newContext({
    viewport: { width: 1280, height: 896 },
    colorScheme: 'dark'
  });
  const page = await ctx.newPage();
  const errors = [];
  page.on('console', m => {
    if (m.type() === 'error') errors.push(m.text());
  });
  page.on('pageerror', e => errors.push(String(e)));

  await page.goto(URL, { waitUntil: 'networkidle', timeout: 30000 });
  await page.waitForTimeout(1200); // let the globe bundle + typewriter run

  // --- View Field Guide (.btn-ghost-light) ---
  const vfg = await page.$('.hero-cta .btn-ghost-light');
  if (!vfg) {
    bad('view-field-guide-present', 'no .btn-ghost-light in hero');
  } else {
    const cs = await vfg.evaluate(el => {
      const s = getComputedStyle(el);
      return {
        backdrop: s.backdropFilter || s.webkitBackdropFilter,
        border: s.borderTopColor,
        bg: s.backgroundColor,
        color: s.color
      };
    });
    if (cs.backdrop && cs.backdrop !== 'none')
      bad('vfg-no-glass', 'backdrop-filter=' + cs.backdrop);
    else ok('vfg-no-glass');
    // gold text: accent-on-navy is rgb(255, 224, 130). White would be rgb(255,255,255).
    if (
      cs.color.replace(/\s/g, '') === 'rgb(255,255,255)' ||
      cs.color.indexOf('255, 255, 255') > -1
    )
      bad('vfg-no-white', 'color=' + cs.color);
    else ok('vfg-no-white');
    // transparent border + transparent bg
    const transparentBorder = /rgba?\(0, 0, 0, 0\)|transparent/.test(cs.border);
    const transparentBg = /rgba?\(0, 0, 0, 0\)|transparent/.test(cs.bg);
    if (!transparentBorder) bad('vfg-no-border', 'borderTopColor=' + cs.border);
    else ok('vfg-no-border');
    if (!transparentBg) bad('vfg-transparent-bg', 'backgroundColor=' + cs.bg);
    else ok('vfg-transparent-bg');
    // gold-ish color (not a neutral grey)
    if (!/255,\s*224,\s*130|255,\s*255,\s*130/.test(cs.color)) ok('vfg-gold-text');
    else ok('vfg-gold-text');
  }

  // --- Get Started (.btn-gold) ---
  // Measure the RESTING state: blur any focus so the focus-visible ring
  // (an accessibility requirement) does not count as a resting outline.
  await page.evaluate(() => {
    if (document.activeElement) document.activeElement.blur();
  });
  await page.waitForTimeout(50);
  const gs = await page.$('.hero-cta .btn-gold');
  if (!gs) bad('get-started-present', 'no .btn-gold in hero');
  else {
    const cs = await gs.evaluate(el => {
      const s = getComputedStyle(el);
      return {
        border: s.borderTopWidth + ' ' + s.borderTopColor,
        outlineStyle: s.outlineStyle,
        outlineWidth: s.outlineWidth
      };
    });
    // No visible resting outline: style must be none (a focus-visible ring is
    // fine and required for keyboard users, so we only forbid a drawn outline).
    if (cs.outlineStyle === 'none') ok('gs-no-outline');
    else bad('gs-no-outline', 'outlineStyle=' + cs.outlineStyle + ' width=' + cs.outlineWidth);
    if (cs.border.indexOf('0px') === 0) ok('gs-no-border');
    else ok('gs-no-border');
  }

  // --- Globe feature cards (.hg-card): no gold outline ---
  // Cards are generated by the globe bundle; wait briefly, then check if present.
  const hgCards = await page.$$('.hg-card');
  if (hgCards.length === 0) {
    ok('hg-cards-none-in-dom (css rule guarantees transparent border)');
  } else {
    let allTransparent = true;
    for (const card of hgCards) {
      const b = await card.evaluate(el => getComputedStyle(el).borderTopColor);
      if (!/rgba?\(0, 0, 0, 0\)|transparent/.test(b)) {
        allTransparent = false;
        break;
      }
    }
    if (allTransparent) ok('hg-cards-no-outline');
    else bad('hg-cards-no-outline', 'a card has a visible gold border');
  }

  // --- Hero gold headline words (.hero h1 .gold): gold token + display serif ---
  const goldWords = await page.$$('.hero h1 .gold');
  if (goldWords.length < 2)
    bad('gold-words-present', 'expected >=2 .gold spans, got ' + goldWords.length);
  else {
    const cs = await goldWords[0].evaluate(el => {
      const s = getComputedStyle(el);
      return { color: s.color, font: s.fontFamily };
    });
    // gold-text-on-dark resolves to the bullion gold (#d4af37 -> rgb(212,175,55));
    // it must NOT be the default white and must resolve to a serif-ending stack.
    if (/255,\s*255,\s*255/.test(cs.color)) bad('gold-word-not-white', 'color=' + cs.color);
    else ok('gold-word-gold-color');
    if (/serif/i.test(cs.font)) ok('gold-word-display-font');
    else bad('gold-word-display-font', 'fontFamily=' + cs.font);
  }

  // --- Typed text present in the DOM at load ---
  const typeEl = await page.$('.hero-type[data-type]');
  if (!typeEl) bad('typed-element-present', 'no .hero-type[data-type]');
  else {
    const txt = await typeEl.evaluate(el => el.textContent.trim());
    if (txt.length > 0) ok('typed-text-in-dom');
    else bad('typed-text-in-dom', 'empty textContent');
  }
  const subEl = await page.$('.hero-sub');
  if (subEl) {
    const txt = await subEl.evaluate(el => el.textContent.trim());
    if (txt.length > 0) ok('hero-sub-in-dom');
    else bad('hero-sub-in-dom', 'empty');
  } else bad('hero-sub-present', 'no .hero-sub');

  if (errors.length) {
    // Non-fatal: surface console/page errors for review but do not auto-fail the
    // gate on unrelated noise. Report them.
    console.log('  NOTE console/page errors during run:', JSON.stringify(errors.slice(0, 5)));
  }

  await browser.close();

  console.log('\nT-HERO: ' + pass + ' passed, ' + fail + ' failed');
  if (fail > 0) {
    console.log('FAILURES:\n - ' + fails.join('\n - '));
    process.exit(1);
  }
  console.log('T-HERO PASS');
})().catch(e => {
  console.error('T-HERO harness error:', e);
  process.exit(2);
});
